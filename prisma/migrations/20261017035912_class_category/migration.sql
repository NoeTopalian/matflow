-- All-or-nothing (see tests/unit/migrations-are-atomic.test.ts).
BEGIN;
-- Bounded waits (see tests/unit/migrations-bounded-waits.test.ts): a lock this file needs that another session
-- holds fails the deploy after 5 s (55P03) instead of queueing every later request on the table behind it; no
-- statement runs past 15 s. Transaction-local: COMMIT or ROLLBACK resets both.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '15s';

-- T6c (Sean note 7): the class category the owner picks on the class form.
--
-- Expand-only. The column is nullable with no default and there is no
-- backfill: every existing class is uncategorised (NULL) and behaves exactly as
-- before. The previous build neither reads nor writes the column, so promoting
-- back is schema-safe (categories written meanwhile are simply not shown).
--
-- The CHECK is the canonical list in lib/class-category.ts CLASS_CATEGORIES.
-- Widening it later is a NEW migration (drop and re-add); this one is never
-- edited once applied. NOT VALID + VALIDATE is kept for the pattern only:
-- inside this one transaction the ADD COLUMN's ACCESS EXCLUSIVE lock is held
-- until COMMIT regardless. Every existing row is NULL, so validation is
-- instant and the lock is brief on a table of this size.

-- AlterTable (generated by prisma migrate diff between the origin/main schema
-- file and the new schema file)
ALTER TABLE "Class" ADD COLUMN     "category" TEXT;

-- The allowed keys. Prisma cannot express a CHECK, so this is hand-written.
ALTER TABLE "Class" ADD CONSTRAINT "Class_category_check"
  CHECK ("category" IS NULL OR "category" IN ('fundamentals', 'gi', 'nogi', 'kids', 'competition', 'open_mat', 'private', 'other')) NOT VALID;
ALTER TABLE "Class" VALIDATE CONSTRAINT "Class_category_check";

COMMIT;
