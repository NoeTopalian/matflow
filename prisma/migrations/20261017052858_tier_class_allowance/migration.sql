-- All-or-nothing (see tests/unit/migrations-are-atomic.test.ts).
BEGIN;
-- Bounded waits (see tests/unit/migrations-bounded-waits.test.ts): a lock this file needs that another session
-- holds fails the deploy after 5 s (55P03) instead of queueing every later request on the table behind it; no
-- statement runs past 15 s. Transaction-local: COMMIT or ROLLBACK resets both.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '15s';

-- T7c (Sean note 5): a membership tier's class allowance, "N classes every M
-- weeks" (rolling window: agent default adopted 17 Oct 2026; not an owner decision.
-- Superseded by the explicit reset basis of 20261021140000, Noe's instruction of 20 Oct 2026). The columns are added
-- here; T7 (lib/checkin.ts, same release) enforces them at every door from the
-- moment a plan has a limit. Through the reader rule it also enforces any tier
-- whose existing "maxClassesPerWeek" is non-null from deploy (as N every 1
-- week), not only once an owner next edits the plan: list those tiers before
-- deploying (read-only query in the T7 PR rollout notes).
--
-- Expand-only. Both columns are nullable with no default and there is NO
-- backfill: every existing tier keeps classLimit/classLimitWeeks NULL, and a
-- non-null "maxClassesPerWeek" is still read as N per 1 week by
-- lib/class-allowance.ts. "maxClassesPerWeek" is neither dropped nor renamed:
-- the previous build reads and edits it, and promoting that build back is
-- schema-safe (its Prisma client selects only the columns it knows; an
-- INSERT from it leaves both new columns NULL, which the CHECKs accept).
--
-- NOT VALID + VALIDATE is kept for the house pattern only: inside this one
-- transaction the ADD COLUMN lock is held until COMMIT regardless. Every
-- existing row is NULL in both columns, so validation is instant.

-- AlterTable (generated by prisma migrate diff between the
-- origin/sean/batch-b-class-access schema file and the new schema file)
ALTER TABLE "MembershipTier" ADD COLUMN     "classLimit" INTEGER,
ADD COLUMN     "classLimitWeeks" INTEGER;

-- Prisma cannot express a CHECK, so these are hand-written. The ranges match
-- CLASS_LIMIT_MAX and CLASS_LIMIT_WEEKS_MAX in lib/class-allowance.ts.
ALTER TABLE "MembershipTier" ADD CONSTRAINT "MembershipTier_classLimit_check"
  CHECK ("classLimit" IS NULL OR ("classLimit" BETWEEN 1 AND 60)) NOT VALID;
ALTER TABLE "MembershipTier" VALIDATE CONSTRAINT "MembershipTier_classLimit_check";

ALTER TABLE "MembershipTier" ADD CONSTRAINT "MembershipTier_classLimitWeeks_check"
  CHECK ("classLimitWeeks" IS NULL OR ("classLimitWeeks" BETWEEN 1 AND 8)) NOT VALID;
ALTER TABLE "MembershipTier" VALIDATE CONSTRAINT "MembershipTier_classLimitWeeks_check";

-- A limit without a period (or the reverse) has no meaning: set together or
-- cleared together.
ALTER TABLE "MembershipTier" ADD CONSTRAINT "MembershipTier_classLimit_pair_check"
  CHECK (("classLimit" IS NULL) = ("classLimitWeeks" IS NULL)) NOT VALID;
ALTER TABLE "MembershipTier" VALIDATE CONSTRAINT "MembershipTier_classLimit_pair_check";

COMMIT;
